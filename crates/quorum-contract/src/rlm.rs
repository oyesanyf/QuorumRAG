//! Recursive Language Models (RLM) data contracts, sub-query structures,
//! and AgentMesh delegation wire formats.

use chrono::Utc;
use quorum_types::AccessTier;
use serde::{Deserialize, Serialize};
use uuid::Uuid;

/// 64-byte Ed25519 signature representation.
pub type Ed25519SignatureBytes = [u8; 64];

/// A retrieved text chunk ingested into the RLM REPL workspace.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct RetrievedChunk {
    pub id: String,
    pub document_id: String,
    pub file_path: String,
    pub line_start: u32,
    pub line_end: u32,
    pub text: String,
    pub score: f32,
    pub access_tier: u8,
    pub source_peer: String,
    #[serde(default)]
    pub node_id: Option<String>,
    #[serde(default)]
    pub is_external: bool,
    #[serde(default)]
    pub node_alias: Option<String>,
    #[serde(default)]
    pub work_cluster_id: Option<String>,
}

/// Configuration parameters and sandbox bounds for RLM execution.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct RlmConfig {
    pub max_iterations: usize,
    pub max_ops: u64,
    pub max_call_depth: usize,
    pub max_string_size: usize,
    pub max_array_size: usize,
    pub timeout_ms: u64,
    pub sub_model: Option<String>,
    pub parallel_sub_queries: usize,
    pub max_output_tokens: usize,
}

impl Default for RlmConfig {
    fn default() -> Self {
        Self {
            max_iterations: 8,
            max_ops: 100_000,
            max_call_depth: 16,
            max_string_size: 1_048_576, // 1 MB
            max_array_size: 4096,
            timeout_ms: 45_000,
            sub_model: None,
            parallel_sub_queries: 4,
            max_output_tokens: 4096,
        }
    }
}

/// Execution trace of a single RLM REPL step.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct RlmStepTrace {
    pub step_number: usize,
    pub code_executed: String,
    pub stdout_output: String,
    pub sub_queries_spawned: Vec<String>,
    pub duration_ms: u64,
}

/// Canonical state-environment actions emitted by the Recursive Language Model (RLM) controller.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "action", rename_all = "snake_case")]
pub enum RlmAction {
    SearchCorpus {
        query: String,
        limit: usize,
    },
    PeekSlice {
        doc_id: String,
        start_byte: usize,
        end_byte: usize,
    },
    RegexGrep {
        doc_id: String,
        pattern: String,
    },
    SpawnSubQuery {
        doc_id: String,
        start_byte: usize,
        end_byte: usize,
        sub_prompt: String,
    },
    FinalAnswer {
        answer: String,
        citations: Vec<GroundedCitation>,
    },
}

/// Exact character/byte-span grounded citation emitted during RLM synthesis.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct GroundedCitation {
    pub document_id: String,
    pub file_path: String,
    pub start_char: usize,
    pub end_char: usize,
    pub cited_text: String,
    pub confidence: f32,
    pub node_id: String,
    #[serde(default)]
    pub is_external: bool,
    #[serde(default)]
    pub node_alias: Option<String>,
    /// Optional provenance rationale explaining how this exact verbatim span grounds the claim.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub rationale: Option<String>,
}

/// Summary and citations contributed by an external mesh peer.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct MeshContribution {
    pub node_id: String,
    #[serde(default)]
    pub node_alias: Option<String>,
    pub summary: String,
    pub citations: Vec<GroundedCitation>,
}

/// Final completion response generated by the RLM engine.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct RlmCompletionResponse {
    pub final_answer: String,
    pub traces: Vec<RlmStepTrace>,
    pub citations: Vec<GroundedCitation>,
    pub mesh_contributions: Vec<MeshContribution>,
    pub total_iterations: usize,
    pub fallback_used: bool,
    pub external_node_ids: Vec<String>,
}

/// Request dispatched across the P2P mesh for delegated RLM sub-queries.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct MeshSubQueryRequest {
    pub capability_token: Vec<u8>,
    pub origin_peer_id: String,
    pub caller_peer_id: String,
    pub hop_index: u8,
    pub max_hops: u8,
    pub sub_query_id: Uuid,
    pub timestamp: i64,
    pub requested_tier: AccessTier,
    pub query_text: String,
    pub embedding: Vec<f32>,
    pub caller_pubkey: [u8; 32],
    #[serde(with = "quorum_types::serde_sig64")]
    pub caller_signature: Ed25519SignatureBytes,
}

impl MeshSubQueryRequest {
    /// Helper to create a new unsigned mesh sub-query request.
    pub fn new(
        caller_peer_id: impl Into<String>,
        query_text: impl Into<String>,
        requested_tier: AccessTier,
    ) -> Self {
        let caller = caller_peer_id.into();
        Self {
            capability_token: Vec::new(),
            origin_peer_id: caller.clone(),
            caller_peer_id: caller,
            hop_index: 0,
            max_hops: 3,
            sub_query_id: Uuid::new_v4(),
            timestamp: Utc::now().timestamp(),
            requested_tier,
            query_text: query_text.into(),
            embedding: Vec::new(),
            caller_pubkey: [0u8; 32],
            caller_signature: [0u8; 64],
        }
    }
}

/// Response returned from a remote peer answering a `MeshSubQueryRequest`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct MeshSubQueryResponse {
    pub sub_query_id: Uuid,
    pub responder_peer_id: String,
    pub chunks: Vec<RetrievedChunk>,
    pub summary: Option<String>,
    pub execution_time_ms: u64,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_rlm_config_defaults() {
        let config = RlmConfig::default();
        assert_eq!(config.max_iterations, 8);
        assert_eq!(config.max_ops, 100_000);
        assert_eq!(config.max_call_depth, 16);
        assert_eq!(config.max_string_size, 1_048_576);
    }

    #[test]
    fn test_mesh_sub_query_request_and_response() {
        let req = MeshSubQueryRequest::new("peer-alpha", "test query", AccessTier::Tier0Public);
        assert_eq!(req.caller_peer_id, "peer-alpha");
        assert_eq!(req.query_text, "test query");

        let serialized = serde_json::to_string(&req).expect("serialize req");
        let deserialized: MeshSubQueryRequest = serde_json::from_str(&serialized).expect("deserialize req");
        assert_eq!(req.sub_query_id, deserialized.sub_query_id);

        let resp = MeshSubQueryResponse {
            sub_query_id: req.sub_query_id,
            responder_peer_id: "peer-beta".to_string(),
            chunks: vec![RetrievedChunk {
                id: "c1".to_string(),
                document_id: "doc1".to_string(),
                file_path: "path/to/doc.pdf".to_string(),
                line_start: 1,
                line_end: 10,
                text: "sample chunk text".to_string(),
                score: 0.95,
                access_tier: 0,
                source_peer: "peer-beta".to_string(),
                node_id: Some("peer-beta".to_string()),
                is_external: true,
                node_alias: Some("Beta Node".to_string()),
                work_cluster_id: Some("doc".to_string()),
            }],
            summary: Some("Summary from beta".to_string()),
            execution_time_ms: 12,
        };

        let resp_json = serde_json::to_string(&resp).expect("serialize resp");
        let resp_de: MeshSubQueryResponse = serde_json::from_str(&resp_json).expect("deserialize resp");
        assert_eq!(resp_de.responder_peer_id, "peer-beta");
        assert_eq!(resp_de.chunks.len(), 1);
        assert!(resp_de.chunks[0].is_external);
    }
}
